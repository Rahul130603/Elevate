const dictionaries: Record<Locale, Dict> = { en, hi, ta, bn, ml, gu, mr };

export function getDict(locale: Locale): Dict {
  return dictionaries[locale];
}

/** Fills `{name}` placeholders: fmt(dict.readOn, { source: "The Hindu" }) */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match,
  );
}

/**
 * Localised name of a section. `top` is the only category id that does not map
 * 1:1 to a dictionary key (it is the front page, `topStories`).
 */
export function categoryLabel(dict: Dict, category: Category): string {
  return category === "top" ? dict.topStories : dict[category];
}
