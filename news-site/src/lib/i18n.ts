/**
 * Locale registry + UI dictionary.
 *
 * Adding a language = add one entry to `localeMeta`, one dictionary below,
 * and one entry to LOCALES. Everything else (routes, nav, switcher, sitemap,
 * hreflang, feeds) is generated from this file.
 */

import type { Category } from "./categories";

export const LOCALES = ["en", "hi", "ta", "bn", "ml", "gu", "mr"] as const;

export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = "en";

export type LocaleMeta = {
  code: Locale;
  /** Name in English, for screen readers and fallbacks. */
  english: string;
  /** Endonym, shown in the language switcher. */
  native: string;
  /** Script name, shown in the footer / language pages. */
  script: string;
  /** BCP-47 tag for Intl formatting. */
  intl: string;
  /** Google News `hl` parameter. */
  hl: string;
  dir: "ltr" | "rtl";
};

export const localeMeta: Record<Locale, LocaleMeta> = {
  en: { code: "en", english: "English", native: "English", script: "Latin", intl: "en-IN", hl: "en", dir: "ltr" },
  hi: { code: "hi", english: "Hindi", native: "हिंदी", script: "Devanagari", intl: "hi-IN", hl: "hi", dir: "ltr" },
  ta: { code: "ta", english: "Tamil", native: "தமிழ்", script: "Tamil", intl: "ta-IN", hl: "ta", dir: "ltr" },
  bn: { code: "bn", english: "Bengali", native: "বাংলা", script: "Bengali", intl: "bn-IN", hl: "bn", dir: "ltr" },
  ml: { code: "ml", english: "Malayalam", native: "മലയാളം", script: "Malayalam", intl: "ml-IN", hl: "ml", dir: "ltr" },
  gu: { code: "gu", english: "Gujarati", native: "ગુજરાતી", script: "Gujarati", intl: "gu-IN", hl: "gu", dir: "ltr" },
  mr: { code: "mr", english: "Marathi", native: "मराठी", script: "Devanagari", intl: "mr-IN", hl: "mr", dir: "ltr" },
};

export const localeCodes = LOCALES as readonly string[];

export function isLocale(value: string | undefined): value is Locale {
  return !!value && localeCodes.includes(value);
}

export function toLocale(value: string | undefined): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

/** `en` -> `/en`, `ta` + `business` -> `/ta/business` */
export function localePath(locale: Locale, segment?: string): string {
  return segment ? `/${locale}/${segment}` : `/${locale}`;
}

