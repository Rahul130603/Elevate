import test from 'node:test';
import assert from 'node:assert/strict';
import { deliverRoutineReminders, saveRoutine, removeRoutine, seedSampleRoutine, readRoutines } from '../../src/services/dailyRoutineService.js';
test('routine save, daily delivery, deduplication, pause and removal', async () => {
  const values = new Map();
  globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
  globalThis.window = { dispatchEvent() {} };
  const now = new Date(2026, 9, 10, 9, 0, 20).getTime();
  values.set('gentize_daily_routines_v1', JSON.stringify([{id: 'routine-water', reason: 'Water', kind: 'interval', time: '09:00', endTime: '09:30', interval: 15, enabled: true, activeFrom: now - 60000}]));
  assert.equal(deliverRoutineReminders(now).length, 1);
  assert.equal(deliverRoutineReminders(now).length, 0);
  assert.equal(deliverRoutineReminders(now + 15 * 60000).length, 1);
  assert.equal(deliverRoutineReminders(new Date(2026, 9, 11, 9, 0, 20).getTime()).length, 1);
  const history = JSON.parse(values.get('gentize_reminder_notifications_v1'));
  assert.equal(history.length, 3); assert.equal(history[0].isDailyRoutine, true);
  assert.ok(history[0].message.includes('Water'));
  await saveRoutine({id: 'routine-water', reason: 'Water', kind: 'interval', time: '09:00', endTime: '09:30', interval: 15, enabled: false});
  assert.equal(deliverRoutineReminders(new Date(2026, 9, 12, 9, 15, 20).getTime()).length, 0);
  await removeRoutine('routine-water');
  assert.deepEqual(JSON.parse(values.get('gentize_daily_routines_v1')), []);
  assert.equal(seedSampleRoutine(), true);
  assert.equal(readRoutines().length, 15);
  const water = readRoutines().find(r => r.id === 'routine-sample-water');
  assert.equal(water.time, '06:00'); assert.equal(water.endTime, '22:00'); assert.equal(water.nativeIds.length, 65);
  assert.equal(new Set(readRoutines().flatMap(r => r.nativeIds)).size, 79);
  assert.equal(seedSampleRoutine(), false);
  await removeRoutine('routine-sample-gym');
  assert.equal(seedSampleRoutine(), false);
  assert.equal(readRoutines().length, 14);
  delete globalThis.localStorage; delete globalThis.window;
});
